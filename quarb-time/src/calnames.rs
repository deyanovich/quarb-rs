//! The calendars' names in the shipped languages (spec: Calendars):
//! for each language and each non-Gregorian calendar the month
//! names by CLDR month code (the leap month's by its own code, a
//! leap year's by the leap-year table) and the era names by ICU
//! era code, the CLDR medium date form of the calendar in that
//! language as a strftime pattern (`%EC` the era name, `%Er` the
//! related Gregorian year, `%EU` the cyclic year name), and the
//! sexagenary year names; then the CLDR's own names of the
//! calendars and of the period grains in each language, the aliases
//! `calendar(NAME)` and `period(GRAIN)` accept. Generated from
//! cldr-json 48.2.0 by the engine's scripts/gen-calnames.py; an
//! ordinary space stands wherever the CLDR writes a no-break or a
//! narrow no-break space.

use crate::calendar::Calendar;

/// One calendar's names in one language.
#[derive(Debug)]
pub struct CalNames {
    pub lang: &'static str,
    pub calendar: Calendar,
    /// (month code, wide name, abbreviation), the leap month under
    /// its own code where the calendar names it.
    pub months: &'static [(&'static str, &'static str, &'static str)],
    /// The names a leap year gives some months instead (Hebrew's
    /// Adar II for M06).
    pub leap_year_months: &'static [(&'static str, &'static str, &'static str)],
    /// The pattern a leap month's name takes where the calendar
    /// derives it (`{0}bis`, `閏{0}`): (wide, abbreviated).
    pub leap_pattern: Option<(&'static str, &'static str)>,
    /// (ICU era code, era name).
    pub eras: &'static [(&'static str, &'static str)],
    /// The CLDR medium date and time form in this calendar.
    pub medium: &'static str,
    /// The sexagenary cycle's sixty year names, where the calendar
    /// counts by them.
    pub cyclic_years: &'static [&'static str],
}

