/// The canonical calendar name an alias denotes, case folded.
pub fn calendar_alias(name: &str) -> Option<&'static str> {
    let n = name.trim().to_lowercase();
    let n = n.split_whitespace().collect::<Vec<_>>().join(" ");
    CALENDAR_ALIASES
        .iter()
        .find(|(a, _)| *a == n)
        .map(|(_, c)| *c)
}

/// The English grain word an alias denotes, case folded.
pub fn grain_alias(name: &str) -> Option<&'static str> {
    let n = name.trim().to_lowercase();
    GRAIN_ALIASES.iter().find(|(a, _)| *a == n).map(|(_, g)| *g)
}
