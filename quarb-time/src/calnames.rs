/// The names of `calendar` in the language of `locale` (its
/// language resolved as the date names are); None for the Gregorian
/// and Julian calendars, whose names are the date names, and for a
/// language no table covers.
pub fn names(locale: &str, calendar: Calendar) -> Option<&'static CalNames> {
    let lang = crate::language(locale);
    let lang = if lang.is_empty() { "en" } else { lang.as_str() };
    ALL.iter()
        .copied()
        .find(|t| t.lang == lang && t.calendar == calendar)
}

