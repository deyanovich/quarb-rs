/// Tags the CLDR resolves to another locale id (its likely
/// subtags): `zh-TW` is Traditional Chinese, `zh-HK` its Hong Kong
/// form.
const ALIASES: &[(&str, &str)] = &[
    ("zh-TW", "zh-Hant"),
    ("zh-Hant-TW", "zh-Hant"),
    ("zh-HK", "zh-Hant-HK"),
    ("zh-MO", "zh-Hant-MO"),
    ("zh-SG", "zh-Hans-SG"),
    ("zh-MY", "zh-Hans-MY"),
    ("zh-CN", "zh"),
    ("zh-Hans", "zh"),
    ("zh-Hans-CN", "zh"),
];

/// The CLDR locale id a tag names: the language lower-cased, a
/// script subtag title-cased, a region upper-cased (`en_gb`,
/// `EN-GB`, `en-GB.UTF-8` all `en-GB`), variants and encodings
/// dropped.
pub fn locale_id(tag: &str) -> String {
    let mut parts = tag
        .trim()
        .split(['.', '@'])
        .next()
        .unwrap_or("")
        .split(['-', '_'])
        .filter(|p| !p.is_empty());
    let mut id = parts.next().unwrap_or("").to_ascii_lowercase();
    for p in parts {
        if p.len() == 4 && p.chars().all(|c| c.is_ascii_alphabetic()) {
            let mut cs = p.chars();
            let head = cs.next().map(|c| c.to_ascii_uppercase()).unwrap_or('X');
            id.push('-');
            id.push(head);
            id.extend(cs.map(|c| c.to_ascii_lowercase()));
        } else if (p.len() == 2 && p.chars().all(|c| c.is_ascii_alphabetic()))
            || (p.len() == 3 && p.chars().all(|c| c.is_ascii_digit()))
        {
            id.push('-');
            id.push_str(&p.to_ascii_uppercase());
        }
    }
    for (from, to) in ALIASES {
        if id == *from {
            return to.to_string();
        }
    }
    id
}

/// The region's tailoring for a tag, if the CLDR has one: the
/// full id first (`zh-Hant-HK`), then the language and script
/// (`zh-Hant`). None for a tag that takes its language's data.
pub fn regional(tag: &str) -> Option<&'static Regional> {
    let id = locale_id(tag);
    let find = |id: &str| REGIONAL.iter().find(|r| r.tag == id);
    if let Some(r) = find(&id) {
        return Some(r);
    }
    // a script with a region: the script alone
    let parts: Vec<&str> = id.split('-').collect();
    if parts.len() == 3 {
        return find(&format!("{}-{}", parts[0], parts[1]));
    }
    None
}
