//! Regional tailoring of the output locale (spec: The Output Locale):
//! for every region of a shipped language where the Unicode CLDR
//! tailors the medium date and time forms, the day periods, the
//! month or weekday names or the number symbols, that region's data;
//! a tag names its region and takes the region's data where it
//! exists, else the language's. Generated from cldr-json
//! 48.2.0 (cldr-dates-full, cldr-numbers-full) by the
//! engine's scripts/gen-regional.py; an ordinary space stands wherever
//! the CLDR writes a no-break or a narrow no-break space in a
//! pattern or a name. Numbers keep the Latin digits throughout.

use crate::datenames::{self, Names};

/// One region's tailoring: the medium instant form as a strftime
/// pattern, the number symbols, and the names (the language's
/// table where the region keeps them).
#[derive(Debug)]
pub struct Regional {
    pub tag: &'static str,
    pub instant: &'static str,
    pub decimal: char,
    pub group: &'static str,
    pub min_grouping: usize,
    pub names: &'static Names,
}

macro_rules! names {
    ($($entry:expr),* $(,)?) => { [$(&$entry),*] };
}

